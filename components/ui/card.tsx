import * as React from "react";
import { cn } from "@/lib/utils";

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  interactive?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, interactive = false, ...props }, ref) => {
    return (
      <div
        ref={ref}
        className={cn(
          "rounded-3xl border border-[#EBE3D5] bg-white/95 p-6 text-brand-text shadow-[0_4px_24px_-6px_rgba(43,36,32,0.06)] transition-all duration-200",
          interactive &&
            "cursor-pointer hover:-translate-y-1 hover:border-brand-primary/40 hover:shadow-[0_12px_32px_-8px_rgba(43,36,32,0.12)] active:translate-y-0",
          className
        )}
        {...props}
      />
    );
  }
);
Card.displayName = "Card";

export const CardHeader = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div ref={ref} className={cn("flex flex-col space-y-1.5 pb-4", className)} {...props} />
));
CardHeader.displayName = "CardHeader";

